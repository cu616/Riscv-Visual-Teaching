// Rebuild bundled templates from pictures/labels, or picture 19 with --named-labels.
// Requires sharp (or --sharp-path).
import { createRequire } from "node:module";
import { readFile, writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import vm from "node:vm";
const require = createRequire(import.meta.url);
const sharpIndex = process.argv.indexOf("--sharp-path");
const sharp = require(sharpIndex >= 0 ? process.argv[sharpIndex + 1] : "sharp");
const root = new URL("../", import.meta.url);
const context = { window: {} };
vm.createContext(context);
for (const file of ["app/src/printed-labels.js", "app/src/vision.js"]) {
  vm.runInContext(await readFile(new URL(file, root), "utf8"), context);
}
if (process.argv.includes("--named-labels")) {
  // Hand-checked sticker rectangles on a 960px-wide view of picture 19.
  // Pictures 20–23 are held out for browser regression.
  const crops = [
    ["main", 186, 224, 102, 53], ["target", 613, 231, 135, 60],
    ["loop", 183, 310, 105, 71], ["start", 626, 329, 104, 53],
    ["end", 192, 410, 87, 54], ["done", 619, 419, 99, 56]
  ];
  const source = fileURLToPath(new URL("pictures/19.jpg", root));
  const factor = (await sharp(source).metadata()).width / 960;
  const samples = [];
  for (const [value, x, y, w, h] of crops) {
    const [left, top, width, height] = [x, y, w, h].map((item) => Math.round(item * factor));
    const data = await sharp(source).extract({ left, top, width, height }).ensureAlpha().raw().toBuffer();
    const printed = context.window.RiscVPrintedLabels;
    const shape = printed.createSignature({ width, height, data });
    if (!shape) throw new Error(`No ink found in template ${value}`);
    samples.push({ kind: "label", category: "label", value, supported: true, ...printed.encodeSignature(shape) });
  }
  await writeFile(new URL("app/src/printed-named-label-templates.js", root),
    `// Generated by scripts/build-printed-labels.mjs --named-labels from pictures/19.jpg.\n(function (global) {\n  global.RiscVNamedLabelTemplates = ${JSON.stringify({ samples })};\n})(typeof window !== "undefined" ? window : globalThis);\n`);
  console.log(`Bundled ${samples.length} named-label templates.`);
  process.exit(0);
}
const categories = context.window.RiscVVision.CATEGORY_OPCODES;
const categoryFor = (value) => Object.keys(categories).find((key) => categories[key].includes(value));
const repeat = (values) => values.flatMap((value) => Array(3).fill(String(value)));
const registerValues = repeat(Array.from({ length: 32 }, (_, i) => `x${i}`));
const immediateValues = repeat(Array.from({ length: 32 }, (_, i) => i));
const sheets = [
  ["5a7a9ff89dfb8eeaf63aad52f39c4829.jpg", "register", registerValues.slice(0, 94)],
  ["7372f16cf6c18ce4d91ca5cf623228ca.jpg", "mixed", [...registerValues.slice(94), ...immediateValues]],
  ["8c3249722571f67fa6e57673c0b3ba03.jpg", "instruction", repeat(["lui", "jal", "jalr", "beq", "bne", "blt", "bge", "bltu", "bgeu", "lb", "lh", "lw", "lbu", "lhu"])],
  ["5bea86b153729effea0b902832ff818e.jpg", "instruction", repeat(["sb", "sh", "sw", "addi", "slti", "sltiu", "xori", "ori", "andi", "slli", "srli", "srai", "add", "sub", "sll"])],
  ["914e1990cf2270bad7dff004cc3335bc.jpg", "instruction", repeat(["slt", "sltu", "xor", "srl", "sra", "or", "and"])]
];
function spans(projection, minimum, maxGap) {
  const result = [];
  let start = -1, last = -1;
  for (let i = 0; i < projection.length; i += 1) {
    if (projection[i] < minimum) continue;
    if (start < 0) start = i;
    else if (i - last > maxGap) { result.push([start, last + 1]); start = i; }
    last = i;
  }
  if (start >= 0) result.push([start, last + 1]);
  return result;
}
const samples = [];
const manifest = [];
for (const [filename, sheetKind, values] of sheets) {
  const path = new URL(`pictures/labels/${filename}`, root);
  const { data, info } = await sharp(fileURLToPath(path)).ensureAlpha().raw().toBuffer({ resolveWithObject: true });
  const left = Math.floor(info.width * 0.13), right = Math.floor(info.width * 0.87);
  const rows = new Uint32Array(info.height);
  const isInk = (x, y) => Math.max(...data.subarray((y * info.width + x) * 4, (y * info.width + x) * 4 + 3)) < 140;
  for (let y = Math.floor(info.height * 0.085); y < info.height * 0.94; y += 1) {
    for (let x = left; x < right; x += 1) if (isInk(x, y)) rows[y] += 1;
  }
  const rowSpans = spans(rows, 12, 18).filter(([top, bottom]) => bottom - top > 35);
  const crops = [];
  for (const [top, bottom] of rowSpans) {
    const columns = new Uint32Array(info.width);
    for (let x = left; x < right; x += 1) {
      for (let y = top; y < bottom; y += 1) if (isInk(x, y)) columns[x] += 1;
    }
    for (const [x, end] of spans(columns, 2, (bottom - top) * 0.6)) {
      if (end - x < 8) continue;
      const rect = { left: x - 4, top: top - 4, width: end - x + 8, height: bottom - top + 8 };
      crops.push(rect);
    }
  }
  if (crops.length !== values.length) throw new Error(`${filename}: expected ${values.length} words, found ${crops.length} (${rowSpans.length} rows)`);
  for (let i = 0; i < crops.length; i += 1) {
    const rect = crops[i];
    const value = values[i];
    const kind = sheetKind === "mixed" ? (i < 2 ? "register" : "immediate") : sheetKind;
    const rgba = await sharp(fileURLToPath(path)).extract(rect).ensureAlpha().raw().toBuffer();
    const signature = context.window.RiscVPrintedLabels.createSignature({ width: rect.width, height: rect.height, data: rgba });
    const category = kind === "instruction" ? categoryFor(value) : kind;
    samples.push({ kind, value, category: category || "unsupported", supported: kind !== "instruction" || Boolean(category), ...context.window.RiscVPrintedLabels.encodeSignature(signature) });
    manifest.push({ file: filename, rect, kind, value });
  }
  console.log(`${filename}: ${crops.length} scanned words`);
}
const bank = { version: 1, source: "pictures/labels", width: 48, height: 32, samples };
await writeFile(new URL("app/src/printed-label-templates.js", root), `// Generated by scripts/build-printed-labels.mjs; do not edit masks by hand.\n(function (global) {\n  global.RiscVPrintedLabelTemplates = ${JSON.stringify(bank)};\n})(typeof window !== "undefined" ? window : globalThis);\n`);
await writeFile(new URL("scripts/printed-label-samples.json", root), JSON.stringify(manifest, null, 2) + "\n");
console.log(`Bundled ${samples.length} print samples.`);
